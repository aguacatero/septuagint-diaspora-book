#!/usr/bin/env python3
"""Generate/check B001's README checkpoint from the authoritative queue and state."""
from __future__ import annotations

import argparse
import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BEGIN = '<!-- BEGIN B001-DRAFT-STATUS (generated by scripts/sync_readme_checkpoint.py) -->'
END = '<!-- END B001-DRAFT-STATUS -->'
CHECKPOINT = re.compile(re.escape(BEGIN) + r'\n.*?\n' + re.escape(END), re.DOTALL)
BACKTICK = chr(96)


def render_checkpoint(root: Path) -> str:
    state = json.loads((root / 'research-queue/B001_NOTEBOOKLM_STATE.json').read_text(encoding='utf-8'))
    with (root / 'research-queue/B001_NOTEBOOKLM_SOURCE_QUEUE.csv').open(newline='', encoding='utf-8') as f:
        queue = list(csv.DictReader(f))
    if not queue:
        raise ValueError('empty B001 source queue')
    ids = [row['source_id'] for row in queue]
    if len(set(ids)) != len(ids):
        raise ValueError('duplicate source IDs in B001 queue')
    source_id = state['active_source_id']
    if source_id not in ids:
        raise ValueError(f'active source {source_id!r} is not in queue')
    accepted = [row for row in queue if row['review_status'] == 'ACCEPTED']
    promoted = [row for row in accepted if row['status'] == 'DONE']
    if any(row['status'] == 'DONE' and row['review_status'] != 'ACCEPTED' for row in queue):
        raise ValueError('DONE source without independent ACCEPTED review')
    last = state.get('last_accepted_source_id')
    if last and last not in {row['source_id'] for row in accepted}:
        raise ValueError(f'last accepted source {last!r} is not accepted in queue')
    active = queue[ids.index(source_id)]
    phase = state['active_phase']
    updated = state['updated_at']
    pr = state['draft_pr']
    return (
        f'**Draft B001 checkpoint (ledger updated {updated}; not merged to {BACKTICK}main{BACKTICK}):** '
        f'**{len(accepted)} of {len(queue)}** queued source packets independently accepted; '
        f'**{len(promoted)}** accepted packets promoted to {BACKTICK}SDP-01 Paul{BACKTICK}. '
        f'**Active source:** {BACKTICK}{source_id}{BACKTICK} ({ids.index(source_id) + 1}/{len(queue)}), '
        f'phase {BACKTICK}{phase}{BACKTICK}, queue {BACKTICK}{active["status"]}{BACKTICK}, review {BACKTICK}{active["review_status"]}{BACKTICK}. '
        f'**Last accepted source:** {BACKTICK}{last or "none"}{BACKTICK}. '
        f'Source-level acceptance does not complete B001 or the TXT milestone. '
        f'[Draft research PR #{pr}](https://github.com/aguacatero/septuagint-diaspora-book/pull/{pr}).'
    )


def sync_readme(root: Path, check: bool = False) -> bool:
    readme_path = root / 'README.md'
    content = readme_path.read_text(encoding='utf-8')
    matches = list(CHECKPOINT.finditer(content))
    if len(matches) != 2:
        raise ValueError(f'expected two B001 checkpoint blocks in README, found {len(matches)}')
    research_pos = content.find('## Research progress\n')
    status_pos = content.find('## Status\n')
    if not (0 <= research_pos < matches[0].start() < status_pos < matches[1].start()):
        raise ValueError('B001 checkpoints must appear once each under Research progress and Status')
    replacement = BEGIN + '\n' + render_checkpoint(root) + '\n' + END
    updated = CHECKPOINT.sub(lambda _: replacement, content)
    if check and updated != content:
        print('README draft checkpoint is stale; run python3 scripts/sync_readme_checkpoint.py')
        return False
    if updated != content:
        readme_path.write_text(updated, encoding='utf-8')
        print('README draft checkpoint synchronized')
    else:
        print('README draft checkpoint verified unchanged')
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if README differs from B001 state/queue')
    args = parser.parse_args()
    try:
        return 0 if sync_readme(ROOT, check=args.check) else 1
    except (OSError, ValueError, KeyError, json.JSONDecodeError) as exc:
        parser.exit(2, f'B001 README checkpoint error: {exc}\n')


if __name__ == '__main__':
    raise SystemExit(main())
